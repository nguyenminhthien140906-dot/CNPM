
-- CollabSphere - Database Schema
-- PostgreSQL; synchronized with database/01-erd.md

CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE SCHEMA IF NOT EXISTS collabsphere;
SET search_path TO collabsphere, public;

-- 1. ROLES
CREATE TABLE IF NOT EXISTS roles (
    role_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name VARCHAR(50) NOT NULL UNIQUE,
    description TEXT
);

-- 2. USERS
CREATE TABLE IF NOT EXISTS users (
    user_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    role_id INT NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    full_name VARCHAR(150) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    phone VARCHAR(20),
    avatar_url TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_users_roles FOREIGN KEY (role_id)
        REFERENCES roles(role_id),
    CONSTRAINT chk_users_email CHECK (POSITION('@' IN email) > 1)
);

-- 3. STUDENTS: user_id is both PK and FK, as in the ERD
CREATE TABLE IF NOT EXISTS students (
    user_id UUID PRIMARY KEY,
    student_code VARCHAR(30) NOT NULL UNIQUE,
    major VARCHAR(100),
    academic_year INT,
    CONSTRAINT fk_students_users FOREIGN KEY (user_id)
        REFERENCES users(user_id) ON DELETE CASCADE,
    CONSTRAINT chk_students_academic_year
        CHECK (academic_year IS NULL OR academic_year > 0)
);

-- 4. LECTURERS
CREATE TABLE IF NOT EXISTS lecturers (
    user_id UUID PRIMARY KEY,
    lecturer_code VARCHAR(30) NOT NULL UNIQUE,
    department VARCHAR(150),
    academic_title VARCHAR(100),
    CONSTRAINT fk_lecturers_users FOREIGN KEY (user_id)
        REFERENCES users(user_id) ON DELETE CASCADE
);

-- 5. STAFF
CREATE TABLE IF NOT EXISTS staff (
    user_id UUID PRIMARY KEY,
    CONSTRAINT fk_staff_users FOREIGN KEY (user_id)
        REFERENCES users(user_id) ON DELETE CASCADE
);

-- 6. HEAD_DEPARTMENTS
CREATE TABLE IF NOT EXISTS head_departments (
    user_id UUID PRIMARY KEY,
    department_name VARCHAR(150) NOT NULL,
    CONSTRAINT fk_head_departments_users FOREIGN KEY (user_id)
        REFERENCES users(user_id) ON DELETE CASCADE
);

-- 7. SUBJECTS
CREATE TABLE IF NOT EXISTS subjects (
    subject_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    subject_code VARCHAR(30) NOT NULL UNIQUE,
    subject_name VARCHAR(200) NOT NULL,
    description TEXT,
    credits INT NOT NULL DEFAULT 3,
    CONSTRAINT chk_subjects_credits CHECK (credits > 0)
);

-- 8. SYLLABUS: one syllabus per subject, as specified by the ERD
CREATE TABLE IF NOT EXISTS syllabus (
    syllabus_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    subject_id UUID NOT NULL UNIQUE,
    title VARCHAR(200) NOT NULL,
    content TEXT NOT NULL,
    version INT NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_syllabus_subjects FOREIGN KEY (subject_id)
    REFERENCES subjects(subject_id) ON DELETE CASCADE,
CONSTRAINT uq_syllabus_id_subject UNIQUE (syllabus_id, subject_id),
CONSTRAINT chk_syllabus_version CHECK (version > 0)
);

-- 9. STUDY_CLASSES
CREATE TABLE IF NOT EXISTS study_classes (
    class_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    lecturer_id UUID NOT NULL,
    class_code VARCHAR(30) NOT NULL UNIQUE,
    class_name VARCHAR(150) NOT NULL,
    subject_id UUID,
    semester VARCHAR(30),
    academic_year VARCHAR(20),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_study_classes_lecturers FOREIGN KEY (lecturer_id)
        REFERENCES lecturers(user_id),
    CONSTRAINT fk_study_classes_subjects FOREIGN KEY (subject_id)
        REFERENCES subjects(subject_id) ON DELETE SET NULL
);

-- 10. CLASS_MEMBERS
CREATE TABLE IF NOT EXISTS class_members (
    class_id UUID NOT NULL,
    student_id UUID NOT NULL,
    joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (class_id, student_id),
    CONSTRAINT fk_class_members_classes FOREIGN KEY (class_id)
        REFERENCES study_classes(class_id) ON DELETE CASCADE,
    CONSTRAINT fk_class_members_students FOREIGN KEY (student_id)
        REFERENCES students(user_id) ON DELETE CASCADE
);

-- 11. PROJECTS
CREATE TABLE IF NOT EXISTS projects (
    project_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    subject_id UUID NOT NULL,
    syllabus_id UUID NOT NULL,
    created_by UUID NOT NULL,
    project_code VARCHAR(30) UNIQUE,
    project_name VARCHAR(200) NOT NULL,
    description TEXT,
    status VARCHAR(30) NOT NULL DEFAULT 'planning',
    start_date DATE,
    end_date DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_projects_syllabus_subject
    FOREIGN KEY (syllabus_id, subject_id)
    REFERENCES syllabus(syllabus_id, subject_id),
    CONSTRAINT fk_projects_users FOREIGN KEY (created_by)
        REFERENCES users(user_id),
    CONSTRAINT chk_projects_dates CHECK (
        end_date IS NULL OR start_date IS NULL OR end_date >= start_date
    ),
    CONSTRAINT chk_projects_status CHECK (
        status IN ('planning', 'in_progress', 'completed', 'cancelled')
    )
);

-- 12. PROJECT_CLASSES
CREATE TABLE IF NOT EXISTS project_classes (
    project_id UUID NOT NULL,
    class_id UUID NOT NULL,
    PRIMARY KEY (project_id, class_id),
    CONSTRAINT fk_project_classes_projects FOREIGN KEY (project_id)
        REFERENCES projects(project_id) ON DELETE CASCADE,
    CONSTRAINT fk_project_classes_classes FOREIGN KEY (class_id)
        REFERENCES study_classes(class_id) ON DELETE CASCADE
);

-- 13. PROJECT_MILESTONES
CREATE TABLE IF NOT EXISTS project_milestones (
    milestone_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    project_id UUID NOT NULL,
    milestone_name VARCHAR(200) NOT NULL,
    description TEXT,
    due_date DATE,
    status VARCHAR(30) NOT NULL DEFAULT 'pending',
    CONSTRAINT fk_milestones_projects FOREIGN KEY (project_id)
        REFERENCES projects(project_id) ON DELETE CASCADE,
    CONSTRAINT chk_milestones_status CHECK (
        status IN ('pending', 'in_progress', 'completed')
    )
);

-- 14. TEAMS: teams belong to a study class according to the ERD
CREATE TABLE IF NOT EXISTS teams (
    team_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    class_id UUID NOT NULL,
    team_name VARCHAR(150) NOT NULL,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_teams_classes FOREIGN KEY (class_id)
        REFERENCES study_classes(class_id) ON DELETE CASCADE,
    CONSTRAINT uq_teams_class_name UNIQUE (class_id, team_name)
);

-- 15. TEAM_MEMBERS
CREATE TABLE IF NOT EXISTS team_members (
    team_id UUID NOT NULL,
    student_id UUID NOT NULL,
    joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_leader BOOLEAN NOT NULL DEFAULT FALSE,
    contribution_percent NUMERIC(5,2) NOT NULL DEFAULT 0,
    PRIMARY KEY (team_id, student_id),
    CONSTRAINT fk_team_members_teams FOREIGN KEY (team_id)
        REFERENCES teams(team_id) ON DELETE CASCADE,
    CONSTRAINT fk_team_members_students FOREIGN KEY (student_id)
        REFERENCES students(user_id) ON DELETE CASCADE,
    CONSTRAINT chk_team_members_contribution
        CHECK (contribution_percent BETWEEN 0 AND 100)
);

-- At most one team leader per team
CREATE UNIQUE INDEX IF NOT EXISTS uq_team_one_leader
    ON team_members(team_id) WHERE is_leader = TRUE;

-- 16. TASKS
CREATE TABLE IF NOT EXISTS tasks (
    task_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    team_id UUID NOT NULL,
    task_name VARCHAR(200) NOT NULL,
    description TEXT,
    status VARCHAR(30) NOT NULL DEFAULT 'todo',
    priority VARCHAR(20) NOT NULL DEFAULT 'medium',
    assigned_to UUID,
    due_date TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_tasks_teams FOREIGN KEY (team_id)
        REFERENCES teams(team_id) ON DELETE CASCADE,
    CONSTRAINT fk_tasks_students FOREIGN KEY (assigned_to)
        REFERENCES students(user_id) ON DELETE SET NULL,
    CONSTRAINT chk_tasks_status CHECK (
        status IN ('todo', 'in_progress', 'review', 'completed', 'cancelled')
    ),
    CONSTRAINT chk_tasks_priority CHECK (priority IN ('low', 'medium', 'high'))
);

-- 17. SUBTASKS
CREATE TABLE IF NOT EXISTS subtasks (
    subtask_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    task_id UUID NOT NULL,
    subtask_name VARCHAR(200) NOT NULL,
    description TEXT,
    status VARCHAR(30) NOT NULL DEFAULT 'todo',
    assigned_to UUID,
    due_date TIMESTAMPTZ,
    CONSTRAINT fk_subtasks_tasks FOREIGN KEY (task_id)
        REFERENCES tasks(task_id) ON DELETE CASCADE,
    CONSTRAINT fk_subtasks_students FOREIGN KEY (assigned_to)
        REFERENCES students(user_id) ON DELETE SET NULL,
    CONSTRAINT chk_subtasks_status CHECK (status IN ('todo', 'in_progress', 'completed'))
);

-- 18. CHECKPOINTS
CREATE TABLE IF NOT EXISTS checkpoints (
    checkpoint_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    team_id UUID NOT NULL,
    checkpoint_name VARCHAR(200) NOT NULL,
    description TEXT,
    due_date TIMESTAMPTZ,
    max_score NUMERIC(5,2) NOT NULL DEFAULT 10,
    status VARCHAR(30) NOT NULL DEFAULT 'pending',
    CONSTRAINT fk_checkpoints_teams FOREIGN KEY (team_id)
        REFERENCES teams(team_id) ON DELETE CASCADE,
    CONSTRAINT chk_checkpoints_max_score CHECK (max_score > 0),
    CONSTRAINT chk_checkpoints_status CHECK (status IN ('pending', 'in_progress', 'completed'))
    status VARCHAR(30) NOT NULL DEFAULT 'pending',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_checkpoints_teams
        FOREIGN KEY (team_id)
        REFERENCES teams(team_id)
        ON DELETE CASCADE,

    CONSTRAINT chk_checkpoints_status
        CHECK (status IN ('pending', 'in_progress', 'completed'))

);

-- 19. CHECKPOINT_SUBMISSIONS
CREATE TABLE IF NOT EXISTS checkpoint_submissions (
    submission_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    checkpoint_id UUID NOT NULL,
    student_id UUID NOT NULL,
    content TEXT NOT NULL,
    submission_url TEXT,
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_submissions_checkpoints FOREIGN KEY (checkpoint_id)
        REFERENCES checkpoints(checkpoint_id) ON DELETE CASCADE,
    CONSTRAINT fk_submissions_students FOREIGN KEY (student_id)
        REFERENCES students(user_id) ON DELETE CASCADE,
    CONSTRAINT uq_checkpoint_student_submission UNIQUE (checkpoint_id, student_id)
);

-- 20. EVALUATIONS
CREATE TABLE IF NOT EXISTS evaluations (
    evaluation_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    team_id UUID NOT NULL,
    evaluator_id UUID NOT NULL,
    target_user_id UUID NOT NULL,
    score NUMERIC(5,2) NOT NULL,
    feedback TEXT,
    evaluated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_evaluations_teams FOREIGN KEY (team_id)
        REFERENCES teams(team_id) ON DELETE CASCADE,
    CONSTRAINT fk_evaluations_evaluator FOREIGN KEY (evaluator_id)
        REFERENCES users(user_id),
    CONSTRAINT fk_evaluations_target_user FOREIGN KEY (target_user_id)
        REFERENCES users(user_id),
    CONSTRAINT chk_evaluations_score CHECK (score >= 0 AND score <= 100),
    CONSTRAINT chk_evaluations_not_self CHECK (evaluator_id <> target_user_id)
);

-- 21. RESOURCES: a resource belongs to either a class or a team
CREATE TABLE IF NOT EXISTS resources (
    resource_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    class_id UUID,
    team_id UUID,
    resource_name VARCHAR(200) NOT NULL,
    resource_url TEXT NOT NULL,
    description TEXT,
    uploaded_by UUID NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_resources_classes FOREIGN KEY (class_id)
        REFERENCES study_classes(class_id) ON DELETE CASCADE,
    CONSTRAINT fk_resources_teams FOREIGN KEY (team_id)
        REFERENCES teams(team_id) ON DELETE CASCADE,
    CONSTRAINT fk_resources_users FOREIGN KEY (uploaded_by)
        REFERENCES users(user_id),
    CONSTRAINT chk_resources_owner CHECK (
        (class_id IS NOT NULL AND team_id IS NULL) OR
        (class_id IS NULL AND team_id IS NOT NULL)
    )
);
-- 22. MILESTONE_QUESTIONS
CREATE TABLE IF NOT EXISTS milestone_questions (
    question_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    milestone_id UUID NOT NULL,
    question_content TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_milestone_questions_milestones
        FOREIGN KEY (milestone_id)
        REFERENCES project_milestones(milestone_id)
        ON DELETE CASCADE
);

-- 23. MILESTONE_ANSWERS
CREATE TABLE IF NOT EXISTS milestone_answers (
    answer_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    question_id UUID NOT NULL,
    student_id UUID NOT NULL,
    answer_content TEXT NOT NULL,
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_milestone_answers_questions
        FOREIGN KEY (question_id)
        REFERENCES milestone_questions(question_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_milestone_answers_students
        FOREIGN KEY (student_id)
        REFERENCES students(user_id)
        ON DELETE CASCADE,
    -- Mỗi sinh viên chỉ có một câu trả lời cho mỗi câu hỏi;
    -- có thể sửa câu trả lời bằng UPDATE.
    CONSTRAINT uq_milestone_answer_student
        UNIQUE (question_id, student_id)
);

-- 24. NOTIFICATIONS
CREATE TABLE IF NOT EXISTS notifications (
    notification_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL,
    notification_type VARCHAR(50) NOT NULL,
    content TEXT NOT NULL,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_notifications_users FOREIGN KEY (user_id)
        REFERENCES users(user_id) ON DELETE CASCADE
);
-- Indexes for common foreign-key lookups
CREATE INDEX IF NOT EXISTS idx_milestone_questions_milestone_id
    ON milestone_questions(milestone_id);
CREATE INDEX IF NOT EXISTS idx_milestone_answers_student_id
    ON milestone_answers(student_id);
CREATE INDEX IF NOT EXISTS idx_users_role_id ON users(role_id);
CREATE INDEX IF NOT EXISTS idx_classes_lecturer_id ON study_classes(lecturer_id);
CREATE INDEX IF NOT EXISTS idx_classes_subject_id ON study_classes(subject_id);
CREATE INDEX IF NOT EXISTS idx_projects_subject_id ON projects(subject_id);
CREATE INDEX IF NOT EXISTS idx_projects_syllabus_id ON projects(syllabus_id);
CREATE INDEX IF NOT EXISTS idx_projects_created_by ON projects(created_by);
CREATE INDEX IF NOT EXISTS idx_project_classes_class_id ON project_classes(class_id);
CREATE INDEX IF NOT EXISTS idx_milestones_project_id ON project_milestones(project_id);
CREATE INDEX IF NOT EXISTS idx_teams_class_id ON teams(class_id);
CREATE INDEX IF NOT EXISTS idx_tasks_team_id ON tasks(team_id);
CREATE INDEX IF NOT EXISTS idx_tasks_assigned_to ON tasks(assigned_to);
CREATE INDEX IF NOT EXISTS idx_checkpoints_team_id ON checkpoints(team_id);
CREATE INDEX IF NOT EXISTS idx_submissions_student_id ON checkpoint_submissions(student_id);
CREATE INDEX IF NOT EXISTS idx_evaluations_target_user_id ON evaluations(target_user_id);
CREATE INDEX IF NOT EXISTS idx_notifications_user_id ON notifications(user_id);
CREATE INDEX IF NOT EXISTS idx_notifications_is_read ON notifications(is_read);

