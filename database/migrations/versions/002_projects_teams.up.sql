-- 002: Projects and teams

CREATE TABLE projects (
    project_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_id BIGINT NOT NULL,
    syllabus_id BIGINT,
    created_by BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL,
    description TEXT,
    goals TEXT,
    expected_outputs TEXT,
    requirements TEXT,
    start_date DATE,
    due_date DATE,
    min_group_size INTEGER NOT NULL DEFAULT 1,
    max_group_size INTEGER NOT NULL DEFAULT 5,
    status VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
    approved_by BIGINT,
    approved_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_projects_dates CHECK (start_date IS NULL OR due_date IS NULL OR start_date <= due_date),
    CONSTRAINT ck_projects_group_size CHECK (min_group_size >= 1 AND max_group_size >= min_group_size),
    CONSTRAINT fk_projects_class FOREIGN KEY (class_id)
        REFERENCES study_classes(class_id) ON DELETE CASCADE,
    CONSTRAINT fk_projects_syllabus FOREIGN KEY (syllabus_id)
        REFERENCES syllabi(syllabus_id) ON DELETE SET NULL,
    CONSTRAINT fk_projects_creator FOREIGN KEY (created_by)
        REFERENCES users(user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_projects_approver FOREIGN KEY (approved_by)
        REFERENCES users(user_id) ON DELETE SET NULL
);

CREATE INDEX idx_projects_class_id ON projects(class_id);
CREATE INDEX idx_projects_created_by ON projects(created_by);

CREATE TRIGGER trg_projects_updated_at
BEFORE UPDATE ON projects
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE teams (
    team_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    team_name VARCHAR(100) NOT NULL,
    leader_student_id BIGINT,
    description TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_teams_project_name UNIQUE (project_id, team_name),
    CONSTRAINT fk_teams_project FOREIGN KEY (project_id)
        REFERENCES projects(project_id) ON DELETE CASCADE,
    CONSTRAINT fk_teams_leader FOREIGN KEY (leader_student_id)
        REFERENCES students(student_id) ON DELETE SET NULL
);

CREATE INDEX idx_teams_project_id ON teams(project_id);

CREATE TABLE team_members (
    team_id BIGINT NOT NULL,
    student_id BIGINT NOT NULL,
    joined_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_team_members PRIMARY KEY (team_id, student_id),
    CONSTRAINT fk_team_members_team FOREIGN KEY (team_id)
        REFERENCES teams(team_id) ON DELETE CASCADE,
    CONSTRAINT fk_team_members_student FOREIGN KEY (student_id)
        REFERENCES students(student_id) ON DELETE CASCADE
);

