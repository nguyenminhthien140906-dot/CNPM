-- 004: Resources, meetings, participants and messages

CREATE TABLE resources (
    resource_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT,
    team_id BIGINT,
    uploaded_by BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL,
    resource_url VARCHAR(1000) NOT NULL,
    resource_type VARCHAR(50),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_resources_single_owner CHECK (
        (project_id IS NOT NULL AND team_id IS NULL) OR
        (project_id IS NULL AND team_id IS NOT NULL)
    ),
    CONSTRAINT fk_resources_project FOREIGN KEY (project_id)
        REFERENCES projects(project_id) ON DELETE CASCADE,
    CONSTRAINT fk_resources_team FOREIGN KEY (team_id)
        REFERENCES teams(team_id) ON DELETE CASCADE,
    CONSTRAINT fk_resources_uploader FOREIGN KEY (uploaded_by)
        REFERENCES users(user_id) ON DELETE RESTRICT
);

CREATE INDEX idx_resources_project_id ON resources(project_id);
CREATE INDEX idx_resources_team_id ON resources(team_id);

CREATE TABLE meetings (
    meeting_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id BIGINT NOT NULL,
    created_by BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL,
    description TEXT,
    meeting_url VARCHAR(500),
    starts_at TIMESTAMP NOT NULL,
    ends_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_meetings_time CHECK (ends_at IS NULL OR ends_at > starts_at),
    CONSTRAINT fk_meetings_team FOREIGN KEY (team_id)
        REFERENCES teams(team_id) ON DELETE CASCADE,
    CONSTRAINT fk_meetings_creator FOREIGN KEY (created_by)
        REFERENCES users(user_id) ON DELETE RESTRICT
);

CREATE INDEX idx_meetings_team_id ON meetings(team_id);
CREATE INDEX idx_meetings_starts_at ON meetings(starts_at);

CREATE TABLE meeting_participants (
    meeting_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    joined_at TIMESTAMP,
    attendance_status VARCHAR(30) NOT NULL DEFAULT 'INVITED',
    CONSTRAINT pk_meeting_participants PRIMARY KEY (meeting_id, user_id),
    CONSTRAINT fk_meeting_participants_meeting FOREIGN KEY (meeting_id)
        REFERENCES meetings(meeting_id) ON DELETE CASCADE,
    CONSTRAINT fk_meeting_participants_user FOREIGN KEY (user_id)
        REFERENCES users(user_id) ON DELETE CASCADE
);

CREATE TABLE messages (
    message_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id BIGINT NOT NULL,
    sender_id BIGINT NOT NULL,
    content TEXT NOT NULL,
    message_type VARCHAR(30) NOT NULL DEFAULT 'TEXT',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_messages_team FOREIGN KEY (team_id)
        REFERENCES teams(team_id) ON DELETE CASCADE,
    CONSTRAINT fk_messages_sender FOREIGN KEY (sender_id)
        REFERENCES users(user_id) ON DELETE RESTRICT
);

CREATE INDEX idx_messages_team_created ON messages(team_id, created_at);

CREATE TRIGGER trg_messages_updated_at
BEFORE UPDATE ON messages
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

