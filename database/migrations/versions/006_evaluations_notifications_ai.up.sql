-- 006: Evaluations, notifications and AI conversations
-- submission_id is included as an optional target to support grading of submissions.

CREATE TABLE evaluations (
    evaluation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluator_user_id BIGINT NOT NULL,
    submission_id BIGINT,
    project_id BIGINT,
    team_id BIGINT,
    student_id BIGINT,
    evaluation_type VARCHAR(30) NOT NULL,
    score NUMERIC(5,2) NOT NULL,
    comment TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_evaluations_score CHECK (score >= 0),
    CONSTRAINT ck_evaluations_single_target CHECK (
        num_nonnulls(submission_id, project_id, team_id, student_id) = 1
    ),
    CONSTRAINT fk_evaluations_evaluator FOREIGN KEY (evaluator_user_id)
        REFERENCES users(user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_evaluations_submission FOREIGN KEY (submission_id)
        REFERENCES submissions(submission_id) ON DELETE CASCADE,
    CONSTRAINT fk_evaluations_project FOREIGN KEY (project_id)
        REFERENCES projects(project_id) ON DELETE CASCADE,
    CONSTRAINT fk_evaluations_team FOREIGN KEY (team_id)
        REFERENCES teams(team_id) ON DELETE CASCADE,
    CONSTRAINT fk_evaluations_student FOREIGN KEY (student_id)
        REFERENCES students(student_id) ON DELETE CASCADE
);

CREATE INDEX idx_evaluations_evaluator ON evaluations(evaluator_user_id);
CREATE INDEX idx_evaluations_submission ON evaluations(submission_id);
CREATE INDEX idx_evaluations_project ON evaluations(project_id);
CREATE INDEX idx_evaluations_team ON evaluations(team_id);
CREATE INDEX idx_evaluations_student ON evaluations(student_id);

CREATE TABLE notifications (
    notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL,
    message TEXT NOT NULL,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_notifications_user FOREIGN KEY (user_id)
        REFERENCES users(user_id) ON DELETE CASCADE
);

CREATE INDEX idx_notifications_user_read_created ON notifications(user_id, is_read, created_at DESC);

CREATE TABLE ai_conversations (
    conversation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    title VARCHAR(200),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_ai_conversations_user FOREIGN KEY (user_id)
        REFERENCES users(user_id) ON DELETE CASCADE
);

CREATE INDEX idx_ai_conversations_user_created ON ai_conversations(user_id, created_at DESC);

CREATE TRIGGER trg_ai_conversations_updated_at
BEFORE UPDATE ON ai_conversations
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE ai_messages (
    ai_message_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL,
    sender_type VARCHAR(20) NOT NULL,
    content TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_ai_messages_conversation FOREIGN KEY (conversation_id)
        REFERENCES ai_conversations(conversation_id) ON DELETE CASCADE
);

CREATE INDEX idx_ai_messages_conversation_created ON ai_messages(conversation_id, created_at);

